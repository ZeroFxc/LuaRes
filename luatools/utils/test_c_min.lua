local luac = require('luac')
print('1. compiling...')
local f = load('return "hello"')
local bc = string.dec(string.dump(f))
print('2. undump...')
local proto = luac.undump(bc, false)
print('3. str_encrypt_c...')
local n = luac.str_encrypt_c(proto)
print('4. changes =', n)
print('5. dump...')
local enc = luac.dump(proto)
print('6. run...')
local r = load(enc)()
print('7. result =', r)
print('OK')
