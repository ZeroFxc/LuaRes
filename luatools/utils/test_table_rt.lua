local luac = require('luac')
local src = 'local t={a=1,b=2,c=3}; t.d=4; local x=t.a; local y=t["b"]; return x+y+t.c+t.d'
local bc = string.dec(string.dump(load(src)))
local p = luac.undump(bc, false)
local fwd = luac.table_obfuscate_c(p)
print("fwd changes:", fwd, "sizecode:", p.sizecode)
local r1 = load(luac.dump(p))()
print("after fwd:", r1)
local rev = luac.detable_obfuscate_c(p)
print("rev changes:", rev, "sizecode:", p.sizecode)
local r2 = load(luac.dump(p))()
print("after rev:", r2)
print(r1 == 10 and r2 == 10 and "PASS" or "FAIL")
