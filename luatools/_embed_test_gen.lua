local luac = require("luac")
local code = [[print(6) print("6") print(true)]]
luac.srand(42)
local p = luac.undump(string.dec(string.dump(load(code), true)), false)
luac.const_hide_c(p); luac.const_shuffle_c(p); luac.str_encrypt_c(p)
luac.num_obfuscate_c(p); luac.opaque_predicate_c(p); luac.luac_obfuscate_c(p)
local embedded = luac.vm_embed_c(p, false)
io.write("embedded len="..#embedded.."\n"); io.flush()
local f = io.open("_embed_test.lua", "w")
f:write(embedded)
f:close()
