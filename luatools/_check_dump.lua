local luac = require("luac")
local f = io.open("../a_vm.lua", "rb")
local src = f:read("*a")
f:close()
local fn = load(src)
local bc = string.dec(string.dump(fn, true))
local p = luac.undump(bc, false)
local dumped = luac.dump(p)
print("dump size:", #dumped)
print("first 4 bytes:", string.byte(dumped, 1), string.byte(dumped, 2), string.byte(dumped, 3), string.byte(dumped, 4))
print("first byte hex:", string.format("0x%02X", string.byte(dumped, 1)))
